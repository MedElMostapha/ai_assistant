export function errorText(code: string, lang: Lang) {
  if (errors[code]) return errors[code][lang === "fr" ? 0 : 1];
  if (code.startsWith("invalid_"))
    return lang === "fr"
      ? "Vérifiez les champs du formulaire."
      : "تحقق من حقول النموذج.";
  return lang === "fr"
    ? "L’opération a échoué. Réessayez ou contactez l’administrateur."
    : "فشلت العملية. أعد المحاولة أو اتصل بالمسؤول.";
}
